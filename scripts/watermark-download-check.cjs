const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { Readable } = require('node:stream');
const axios = require('axios');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wm-download-'));
const { WatermarkService } = require('../dist/services/watermark');
const service = new WatermarkService();
const original = axios.get;
const error = (status, code) => Object.assign(new Error('sensitive URL must not leak'), { isAxiosError: true, code, response: status ? { status } : undefined });
(async () => {
  let attempts = 0;
  axios.get = async () => { if (++attempts === 1) throw error(503); return { data: Readable.from(['ok']) }; };
  const file = path.join(root, 'file');
  await service.download('https://invalid.test/secret', file, 20);
  assert.equal(attempts, 2); assert.equal(fs.readFileSync(file, 'utf8'), 'ok');
  attempts = 0;
  axios.get = async () => { attempts++; throw error(404); };
  await assert.rejects(service.download('https://invalid.test/secret', file, 20), /HTTP 404/);
  assert.equal(attempts, 1);
  attempts = 0;
  axios.get = async () => { attempts++; return { data: Readable.from(['way-too-large']) }; };
  await assert.rejects(service.download('https://invalid.test/secret', file, 2), /超过下载上限/);
  assert.equal(attempts, 1);
  attempts = 0;
  axios.get = async () => { attempts++; throw error(undefined, 'ECONNRESET'); };
  await assert.rejects(service.download('https://invalid.test/secret', file, 20), e => e.message.includes('ECONNRESET') && !e.message.includes('secret'));
  assert.equal(attempts, 2);
  console.log('PASS download transient retry, permanent failure no retry, size guard, redaction and bounded attempts');
})().then(()=>{axios.get=original;process.exit(0)},e=>{axios.get=original;console.error(e);process.exit(1)});
